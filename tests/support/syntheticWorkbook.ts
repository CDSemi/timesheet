/** Valid worksheet XML padded with a comment so it compresses like zeros but still parses. */
export function paddedSheetXml(bytes: number): string {
  const head = '<?xml version="1.0" encoding="UTF-8"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData/></worksheet><!--';
  const tail = '-->';
  return head + 'A'.repeat(Math.max(0, bytes - head.length - tail.length)) + tail;
}

/** Overwrite header fields of one entry (central directory and local header) without touching its data. */
export function patchEntry(
  bytes: Uint8Array,
  name: string,
  fields: { uncompressedSize?: number; crc?: number; flags?: number },
): Uint8Array {
  const copy = new Uint8Array(bytes);
  const view = new DataView(copy.buffer);
  let eocd = copy.length - 22;
  while (eocd >= 0 && view.getUint32(eocd, true) !== 0x06054b50) eocd -= 1;
  const count = view.getUint16(eocd + 10, true);
  let at = view.getUint32(eocd + 16, true);
  for (let index = 0; index < count; index += 1) {
    const nameLength = view.getUint16(at + 28, true);
    const extraLength = view.getUint16(at + 30, true);
    const commentLength = view.getUint16(at + 32, true);
    const entryName = new TextDecoder().decode(copy.subarray(at + 46, at + 46 + nameLength));
    if (entryName === name) {
      const local = view.getUint32(at + 42, true);
      if (fields.uncompressedSize !== undefined) {
        view.setUint32(at + 24, fields.uncompressedSize, true);
        view.setUint32(local + 22, fields.uncompressedSize, true);
      }
      if (fields.crc !== undefined) {
        view.setUint32(at + 16, fields.crc, true);
        view.setUint32(local + 14, fields.crc, true);
      }
      if (fields.flags !== undefined) {
        view.setUint16(at + 8, fields.flags, true);
        view.setUint16(local + 6, fields.flags, true);
      }
      return copy;
    }
    at += 46 + nameLength + extraLength + commentLength;
  }
  throw new Error(`Entry ${name} not found`);
}
