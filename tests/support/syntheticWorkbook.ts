import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { strFromU8, strToU8, unzipSync, zipSync, type Zippable } from 'fflate';
import { addDays, toDayNumber, type CivilDate } from '../../src/domain/dates.ts';

/*
 * Test-only synthetic workbooks (WP4-T08). Everything happens in memory: the tracked template is read, its ZIP
 * entries are cloned and extended with synthetic dated sheets, and the bytes are handed straight to the reader.
 * No spreadsheet library re-saves the template, and no generated workbook is written to disk or committed.
 * Names are fictional, addresses are on example.invalid and every date comes from the callers (a fixed 2026
 * test range); nothing here reads the wall clock.
 */

export const TEMPLATE_PATH = fileURLToPath(new URL('../../reference/inputs/Timesheet_Rev8_2026.xlsx', import.meta.url));
export const TEMPLATE_SHA256 = '47ef42d5e4a9b7aea0be545ed563d3d22987609b59bd846c1c08dec2d29c6331';

/** Fixed ZIP timestamp so generated bytes do not depend on when a test runs (2026-01-01T00:00:00Z). */
const FIXED_MTIME = 1_767_225_600_000;
const EXCEL_EPOCH_OFFSET = 25_569;

export function sha256Hex(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex');
}

export function readTemplateBytes(): Uint8Array {
  return new Uint8Array(readFileSync(TEMPLATE_PATH));
}

export type Entries = Record<string, Uint8Array>;

export function unpack(bytes: Uint8Array): Entries {
  return unzipSync(bytes);
}

export function pack(entries: Entries): Uint8Array {
  const zippable: Zippable = {};
  for (const [name, data] of Object.entries(entries)) zippable[name] = [data, { level: 6, mtime: FIXED_MTIME }];
  return zipSync(zippable);
}

/** ZIP-level edit: replace or add one entry's text and return new package bytes. */
export function withText(bytes: Uint8Array, name: string, change: (text: string | null) => string): Uint8Array {
  const entries = unpack(bytes);
  const current = entries[name];
  entries[name] = strToU8(change(current === undefined ? null : strFromU8(current)));
  return pack(entries);
}

export function withEntry(bytes: Uint8Array, name: string, data: Uint8Array): Uint8Array {
  return pack({ ...unpack(bytes), [name]: data });
}

function escapeXml(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

