// Dated sheets

export type SyntheticDay = {
  label?: string;
  /** Write the label as a formula with this cached result instead of a plain string. */
  labelFormulaCache?: string;
  /** Clock cells as minutes since midnight. */
  start?: number;
  end?: number;
  /** Override the date cell (a civil date) or blank it with `null`. */
  date?: CivilDate | null;
};

export type SyntheticPeriod = {
  payrollDate: CivilDate;
  /** Defaults to `YYYY.MM.DD` of the payroll date. */
  sheetName?: string;
  employee?: string;
  /** Day overrides by index 0..13 (Monday of week 1 .. Sunday of week 2). */
  days?: Readonly<Record<number, SyntheticDay>>;
  /** Replace the inherited formulas (8.5 hours, X24 without Sunday, TODAY in W26) with corrected ones. */
  cleanFormulas?: boolean;
  /** Payroll date written in I10 when it should differ from the sheet name. */
  payrollCellDate?: CivilDate;
  hidden?: boolean;
};

const DAY_COLUMNS = ['B', 'F', 'J', 'N', 'R', 'V', 'Z'];
const COLUMN_AFTER = (letters: string, steps: number): string => {
  let value = 0;
  for (const letter of letters) value = value * 26 + (letter.charCodeAt(0) - 64);
  value += steps;
  let result = '';
  while (value > 0) {
    result = String.fromCharCode(65 + ((value - 1) % 26)) + result;
    value = Math.floor((value - 1) / 26);
  }
  return result;
};

function serial(date: CivilDate): number {
  return toDayNumber(date) + EXCEL_EPOCH_OFFSET;
}

const CELL_PATTERN = (address: string): RegExp => new RegExp(`<c r="${address}"([^>]*?)(?:/>|>[\\s\\S]*?</c>)`);

/** Replace one cell, keeping its style index. `build(styleAttr)` returns the new `<c>` element. */
function setCell(xml: string, address: string, build: (style: string) => string): string {
  const pattern = CELL_PATTERN(address);
  const match = pattern.exec(xml);
  if (match === null) throw new Error(`Template cell ${address} not found`);
  const style = /\ss="(\d+)"/.exec(match[1] ?? '')?.[0] ?? '';
  return xml.replace(pattern, () => build(style));
}

const text = (address: string, value: string) => (style: string) =>
  `<c r="${address}"${style} t="inlineStr"><is><t>${escapeXml(value)}</t></is></c>`;
const number = (address: string, value: number) => (style: string) => `<c r="${address}"${style}><v>${value}</v></c>`;
const blank = (address: string) => (style: string) => `<c r="${address}"${style}/>`;

function buildPeriodSheet(templateSheet: string, period: SyntheticPeriod): string {
  let xml = templateSheet.replace(' tabSelected="1"', '');
  xml = setCell(xml, 'I10', number('I10', serial(period.payrollCellDate ?? period.payrollDate)));
  xml = setCell(xml, 'I8', text('I8', period.employee ?? 'Test Person Alpha (alpha@example.invalid)'));
  const periodStart = addDays(period.payrollDate, -18);

  for (let index = 0; index < 14; index += 1) {
    const week = index < 7 ? { date: 13, label: 14, clock: 15, hours: 16 } : { date: 20, label: 21, clock: 22, hours: 23 };
    const column = DAY_COLUMNS[index % 7] ?? 'B';
    const override = period.days?.[index];
    const date = override !== undefined && 'date' in override ? override.date : addDays(periodStart, index);
    const dateAddress = `${column}${week.date}`;
    xml = setCell(xml, dateAddress, date === null || date === undefined ? blank(dateAddress) : number(dateAddress, serial(date)));

    const labelAddress = `${column}${week.label}`;
    if (override?.labelFormulaCache !== undefined) {
      const cached = override.labelFormulaCache;
      xml = setCell(xml, labelAddress, (style) =>
        `<c r="${labelAddress}"${style} t="str"><f>IFERROR(VLOOKUP(${dateAddress},'Holiday Dates'!$A$1:$B$100,2,FALSE),"Worked")</f><v>${escapeXml(cached)}</v></c>`);
    } else if (override?.label !== undefined) {
      xml = setCell(xml, labelAddress, text(labelAddress, override.label));
    } else if (index % 7 < 5) {
      xml = setCell(xml, labelAddress, text(labelAddress, 'Worked'));
    }

    const startAddress = `${column}${week.clock}`;
    const endAddress = `${COLUMN_AFTER(column, 2)}${week.clock}`;
    if (override?.start !== undefined) xml = setCell(xml, startAddress, number(startAddress, override.start / 1440));
    if (override?.end !== undefined) xml = setCell(xml, endAddress, number(endAddress, override.end / 1440));

    if (period.cleanFormulas === true) xml = setCell(xml, `${column}${week.hours}`, blank(`${column}${week.hours}`));
  }

  if (period.cleanFormulas === true) {
    xml = setCell(xml, 'X24', (style) => `<c r="X24"${style}><f>SUM($B$16:$AC$16)+SUM($B$23:$AC$23)</f><v>0</v></c>`);
    xml = setCell(xml, 'W26', number('W26', serial(period.payrollDate)));
  }
  return xml;
}

export type SyntheticWorkbookOptions = {
  periods: readonly SyntheticPeriod[];
  /** Template bytes; defaults to the tracked sanitized template. */
  template?: Uint8Array;
};

/**
 * Clone the template's ZIP entries and add one synthetic dated sheet per period. Each new sheet is a copy of the
 * template `Timesheet` sheet (so it carries the same inherited formulas unless `cleanFormulas` is set).
 */
export function buildSyntheticWorkbook(options: SyntheticWorkbookOptions): Uint8Array {
  const entries = unpack(options.template ?? readTemplateBytes());
  const templateSheet = strFromU8(entries['xl/worksheets/sheet3.xml'] ?? new Uint8Array());
  const sheetRels = entries['xl/worksheets/_rels/sheet3.xml.rels'];
  let workbook = strFromU8(entries['xl/workbook.xml'] ?? new Uint8Array());
  let relationships = strFromU8(entries['xl/_rels/workbook.xml.rels'] ?? new Uint8Array());
  let contentTypes = strFromU8(entries['[Content_Types].xml'] ?? new Uint8Array());

  options.periods.forEach((period, offset) => {
    const part = `xl/worksheets/sheet${100 + offset}.xml`;
    const name = period.sheetName ?? period.payrollDate.replace(/-/g, '.');
    const relId = `rIdSyn${offset}`;
    entries[part] = strToU8(buildPeriodSheet(templateSheet, period));
    if (sheetRels !== undefined) entries[`xl/worksheets/_rels/sheet${100 + offset}.xml.rels`] = sheetRels;
    const state = period.hidden === true ? ' state="hidden"' : '';
    workbook = workbook.replace('</sheets>', `<sheet name="${escapeXml(name)}" sheetId="${200 + offset}"${state} r:id="${relId}"/></sheets>`);
    relationships = relationships.replace(
      '</Relationships>',
      `<Relationship Id="${relId}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet${100 + offset}.xml"/></Relationships>`,
    );
    contentTypes = contentTypes.replace(
      '</Types>',
      `<Override PartName="/${part}" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>`,
    );
  });
  entries['xl/workbook.xml'] = strToU8(workbook);
  entries['xl/_rels/workbook.xml.rels'] = strToU8(relationships);
  entries['[Content_Types].xml'] = strToU8(contentTypes);
  return pack(entries);
}

/** A sheet with an arbitrary name in the same worksheet-clone mold (used for non-date sheet names). */
export function buildNamedSheetWorkbook(names: readonly string[], base?: Uint8Array): Uint8Array {
  return buildSyntheticWorkbook({
    template: base,
    periods: names.map((sheetName, index) => ({ payrollDate: addDays('2026-01-09', 14 * index), sheetName })),
  });
}

